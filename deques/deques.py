# A deque is just a double-ended queue -- you can add to the front or back,
# and remove from the front or back.
# * addFront(element)
# * addBack(element)
# * removeFront()
# * removeBack()
# * size()
#
# operations are O(1) with a linked list, not so great under array-based list
# As a "fun" exercise, you can try and implement a deque with an array-based list and
